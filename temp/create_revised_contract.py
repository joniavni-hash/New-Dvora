def add_rtl_para(doc, text, bold=False, alignment=WD_ALIGN_PARAGRAPH.RIGHT, size=None, color=None):
    p = doc.add_paragraph()
    p.alignment = alignment
    # Set RTL
    pPr = p._element.get_or_add_pPr()
    from docx.oxml.ns import qn
    bidi = pPr.makeelement(qn('w:bidi'), {})
    pPr.append(bidi)
    run = p.add_run(text)
    run.bold = bold
    if size:
        run.font.size = size
    if color:
        run.font.color.rgb = color
    return p, run

def add_change_note(doc, text):
    """Add a red highlighted change note"""
    p, run = add_rtl_para(doc, text, color=RGBColor(0xCC, 0x00, 0x00), size=Pt(10))
    return p

